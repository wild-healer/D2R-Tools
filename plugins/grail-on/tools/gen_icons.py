# Builds src/icons.inc: the category and menu icons, from game-icons.net
# (CC BY 3.0, https://game-icons.net, see src/art/ICONS-CREDITS.txt) as
# packaged in @iconify-json/game-icons. Each icon is a 98x98 coverage mask
# (one byte per pixel); the plugin colours it when it registers the sprites.
# Usage: python3 gen_icons.py <icons.json> <out.inc>
import io, json, sys
import cairosvg
from PIL import Image

# plugin name -> game-icons name
ICONS = {
    # armor
    "helm": "visored-helm", "tors": "breastplate", "shld": "round-shield", "glov": "gauntlet", "boot": "boots", "belt": "belt",
    "barb": "horned-helm", "drui": "wolf-head", "pala": "templar-shield", "necr": "totem-head", "warl": "evil-book",
    # weapons
    "axe": "battle-axe", "bow": "pocket-bow", "assn": "wolverine-claws", "xbow": "crossbow", "knif": "plain-dagger", "jave": "stone-spear",
    "blun": "spiked-mace", "sorc": "crystal-ball", "pole": "halberd", "scep": "winged-scepter", "spea": "trident", "staf": "wizard-staff",
    "swor": "broadsword", "thro": "thrown-daggers", "wand": "crystal-wand",
    # accessories
    "char": "rune-stone", "amul": "gem-pendant", "ring": "ring", "jewl": "cut-diamond", "other": "swap-bag",
    # class sets, in SetRules order: ama ass bar dru nec pal sor war
    "cls0": "woman-elf-face", "cls1": "ninja-head", "cls2": "barbarian", "cls3": "bear-head", "cls4": "dread-skull", "cls5": "black-knight-helm",
    "cls6": "witch-face", "cls7": "warlock-hood",
    # set tiers
    "tier0": "rank-1", "tier1": "rank-2", "tier2": "rank-3",
    # menus
    "stats": "histogram", "grail": "holy-grail", "weapons": "crossed-swords", "armor": "chest-armor", "sets": "linked-rings", "runewords": "rune-sword", "config": "cog",
}
SIZE = 98

data = json.load(open(sys.argv[1]))
width, height = data.get("width", 512), data.get("height", 512)
out = ["// Generated by tools/gen_icons.py from game-icons.net (CC BY 3.0). Do not edit.",
       f"constexpr int IconSize = {SIZE};", "struct IconMask { const char* name; const unsigned char* alpha; };"]
names = []
for key, icon in ICONS.items():
    body = data["icons"][icon]["body"].replace("currentColor", "#fff")
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{SIZE}" height="{SIZE}">{body}</svg>'
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=SIZE, output_height=SIZE)
    alpha = Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A").tobytes()
    ident = "Icon_" + key
    out.append(f"constexpr unsigned char {ident}[] {{")
    for i in range(0, len(alpha), 32):
        out.append("\t" + ",".join(str(b) for b in alpha[i:i + 32]) + ",")
    out.append("};")
    names.append((key, ident))
out.append("constexpr IconMask IconMasks[] {")
out += [f'\t{{ "{k}", {i} }},' for k, i in names]
out.append("};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print(len(names), "icons")
