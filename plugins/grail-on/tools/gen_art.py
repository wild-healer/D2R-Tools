#!/usr/bin/env python3
"""Writes src/builtin_art.inc: item art the plugin uses when the active mod has no
data/hd/items/items.json of its own, and unique art from the Item Dictionary mod.

Usage: gen_art.py <items.json> <tables.inc from gen_tables.py> <uniqueitems.txt> <output .inc>
"""
import csv, json, re, sys

items_json, tables, uniques_txt, out = sys.argv[1:5]
assets = {}
for entry in json.load(open(items_json, encoding='utf-8')):
    for code, value in entry.items():
        assets.setdefault(code, value['asset'])
unique_art = {}
for m in re.finditer(r'\{ \d+, (\d+), \d, \d, \d, \w+, "(?:[^"\\]|\\.)*", "(?:[^"\\]|\\.)*", "([^"]*)", "([^"]*)", "([^"]*)" \}', open(tables).read()):
    row, code, ghost, art = m.groups()
    if art and art != ghost: unique_art[int(row)] = art
index = {int(r['*ID']): r['index'] for r in csv.DictReader(open(uniques_txt, encoding='utf-8', errors='replace'), delimiter='\t') if r['*ID']}
key = lambda name: re.sub(r'[^a-z0-9]', '', name.lower())
lines = ['// Generated by tools/gen_art.py: the item art the plugin falls back on when the',
         '// active mod has no data/hd/items/items.json of its own, and unique art from the Item Dictionary mod.',
         '// { item code, asset under items/<weapon|armor|misc>/ }', 'const AssetEntry BaseAssets[] {']
lines += [f'\t{{ "{c}", "{a}" }},' for c, a in assets.items()]
lines += ['};', '', '// { unique index (lowercase letters and digits only), sprite }', 'const AssetEntry UniqueAssets[] {']
lines += [f'\t{{ "{key(index[r])}", "{a}" }},' for r, a in sorted(unique_art.items()) if r in index]
open(out, 'w').write('\n'.join(lines + ['};', '']))
