#!/usr/bin/env python3
"""Native-looking art for the grail view, cut from D2R's own stash sprite.

gen:     art.py gen <AdvancedStash_Expanded.sprite> <out art.inc>
preview: art.py preview <AdvancedStash_Expanded.sprite> <BasicStash_Expanded.sprite> <out.png>

The plugin rebuilds every sprite it needs from two pieces at load:
- the colour of the stash's plain background (a 200x200 patch), drawn as fine stone grain;
- a 98x98 empty slot: its corners and frame edges, stretched to any tile size,
  around a grained inside of the slot's own colour.
"""
import struct, sys
from PIL import Image

PATCH = (220, 1420, 200, 200)  # plain background, the smoothest spot of the sprite
SLOT = (98, 910, 98, 98)       # an empty 1x1 gem slot
CORNER = 12                    # 9-slice border kept as is

def load(path):
    b = open(path, 'rb').read()
    w = struct.unpack_from('<I', b, 8)[0]
    h = struct.unpack_from('<I', b, 12)[0]
    return Image.frombytes('RGBA', (w, h), b[40:40 + w * h * 4])

def crop(im, r):
    x, y, w, h = r
    return im.crop((x, y, x + w, y + h))

# The same algorithms the plugin uses (keep in sync with plugin.cpp).
def noise(x, y, seed):
    # Small integer hash: the fine grain of the game's dark stone, without a visible repeat.
    h = (x * 374761393 + y * 668265263 + seed * 2246822519) & 0xFFFFFFFF
    h = ((h ^ (h >> 13)) * 1274126177) & 0xFFFFFFFF
    return ((h ^ (h >> 16)) & 0xFF) / 255.0

def stone(w, h, color, grain, seed):
    out = Image.new('RGBA', (w, h))
    px = out.load()
    for y in range(h):
        for x in range(w):
            # Two octaves: single pixels and 3x3 blotches.
            n = 0.6 * noise(x, y, seed) + 0.4 * noise(x // 3, y // 3, seed + 1) - 0.5
            px[x, y] = tuple(max(0, min(255, int(c + n * grain))) for c in color) + (255,)
    return out

def mean(im):
    data = list(im.get_flattened_data()) if hasattr(im, 'get_flattened_data') else list(im.getdata())
    return tuple(sum(p[i] for p in data) // len(data) for i in range(3))

def slot(src, w, h):
    s, c = src.size[0], CORNER
    out = stone(w, h, mean(src.crop((c, c, s - c, s - c))), 10, 7)
    # Corners as they are, edges stretched from the slot's middle row/column.
    for ox, ix in ((0, 0), (w - c, s - c)):
        for oy, iy in ((0, 0), (h - c, s - c)):
            out.paste(src.crop((ix, iy, ix + c, iy + c)), (ox, oy))
    top, bottom = src.crop((s // 2, 0, s // 2 + 1, c)), src.crop((s // 2, s - c, s // 2 + 1, s))
    left, right = src.crop((0, s // 2, c, s // 2 + 1)), src.crop((s - c, s // 2, s, s // 2 + 1))
    for x in range(c, w - c):
        out.paste(top, (x, 0)); out.paste(bottom, (x, h - c))
    for y in range(c, h - c):
        out.paste(left, (0, y)); out.paste(right, (w - c, y))
    return out

def main():
    adv = load(sys.argv[2])
    patch, src = crop(adv, PATCH), crop(adv, SLOT)
    if sys.argv[1] == 'gen':
        with open(sys.argv[3], 'w') as f:
            f.write('// Generated by tools/art.py from D2R\'s stash sprite.\n')
            f.write('constexpr int BackgroundColor[3] { %d, %d, %d };\n' % mean(patch))
            f.write(f'constexpr int SlotSize = {SLOT[2]}, SlotCorner = {CORNER};\n')
            f.write('// The empty slot, RGBA rows.\nconst unsigned char SlotPixels[] = {\n')
            data = src.tobytes()
            for i in range(0, len(data), 32):
                f.write(','.join(str(v) for v in data[i:i + 32]) + ',\n')
            f.write('};\n')
    else:
        base = load(sys.argv[3])
        base.paste(stone(1571, 1570, mean(patch), 12, 3), (57, 175))
        for (x, y, w, h) in ((1, 1, 1, 3), (4, 1, 2, 3), (7, 1, 2, 4), (10, 1, 1, 1), (13, 1, 2, 2), (1, 6, 2, 1)):
            base.paste(slot(src, w * 98, h * 98), (58 + x * 98, 177 + y * 98))
        base.convert('RGB').save(sys.argv[4])

main()
