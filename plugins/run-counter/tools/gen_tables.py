#!/usr/bin/env python3
"""Generates src/tables.inc from the game's excel folder.

Usage: python3 tools/gen_tables.py <excel dir> > src/tables.inc

The plugin gets row numbers and item codes from D2RLoader; these tables turn
them into string keys (looked up in the game's own strings at run time) with an
English fallback.
"""
import csv
import sys
from pathlib import Path


def rows(folder, name):
    with open(Path(folder) / name, encoding="latin-1", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def n(text):
    return text if text and text.lstrip("-").isdigit() else "0"


def c(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(folder):
    out = ["// Generated by tools/gen_tables.py from the game's excel folder. Do not edit.", ""]

    # UniqueItems / SetItems: compiled row = *ID (spacer rows have no *ID).
    for table, file, code_col in (("UniqueRows", "uniqueitems.txt", "code"), ("SetRows", "setitems.txt", "item")):
        out.append(f"constexpr RecordName {table}[] {{")
        for r in rows(folder, file):
            if r.get("*ID", "").isdigit() and r[code_col]:
                out.append(f"\t{{ {r['*ID']}, {c(r[code_col])}, {c(r['index'])} }},")
        out.append("};")
        out.append("")

    # Weapons, armor and misc: item code -> name string key, English name.
    out.append("constexpr BaseName Bases[] {")
    seen = set()
    for file in ("weapons.txt", "armor.txt", "misc.txt"):
        for r in rows(folder, file):
            code = r.get("code", "")
            if code and code not in seen and r.get("namestr"):
                seen.add(code)
                out.append(f"\t{{ {c(code)}, {c(r['namestr'])}, {c(r['name'])} }},")
    out.append("};")
    out.append("")

    # Levels: id -> name string key, English name, town flag, monster level
    # per difficulty (MonLvlEx: the expansion's levels).
    towns = {"1", "40", "75", "103", "109"}
    out.append("constexpr LevelName Levels[] {")
    for r in rows(folder, "levels.txt"):
        if r["Id"].isdigit() and r["Id"] != "0":
            key = r["LevelName"] or r["*StringName"]
            mlvl = ", ".join(n(r.get(col)) for col in ("MonLvlEx", "MonLvlEx(N)", "MonLvlEx(H)"))
            out.append(f"\t{{ {r['Id']}, {c(key)}, {c(r['*StringName'] or key)}, {'true' if r['Id'] in towns else 'false'}, {{ {mlvl} }} }},")
    out.append("};")
    out.append("")

    # Bosses (MonStats boss = 1): class id -> name string key, monster level
    # per difficulty (their drops have that item level).
    out.append("constexpr MonsterName Bosses[] {")
    for r in rows(folder, "monstats.txt"):
        if r.get("boss") == "1" and r.get("*hcIdx", "").isdigit():
            mlvl = ", ".join(n(r.get(col)) for col in ("Level", "Level(N)", "Level(H)"))
            out.append(f"\t{{ {r['*hcIdx']}, {c(r['NameStr'])}, {{ {mlvl} }} }},")
    out.append("};")
    out.append("")

    # Item classes: code -> group, equipment slot, tier, gem kind and grade.
    # See ItemClass in plugin.cpp for the numbers.
    types = {r["Code"]: r for r in rows(folder, "itemtypes.txt") if r.get("Code")}

    def is_a(t, want, depth=0):
        if not t or depth > 8:
            return False
        if t == want:
            return True
        r = types.get(t)
        return bool(r) and (is_a(r.get("Equiv1"), want, depth + 1) or is_a(r.get("Equiv2"), want, depth + 1))

    def any_of(r, wanted):
        return any(is_a(r.get(col), w) for col in ("type", "type2") for w in wanted)

    slots = [("ring", 8), ("amul", 9), ("helm", 1), ("tors", 2), ("glov", 5), ("belt", 6), ("boot", 7), ("shld", 4), ("weap", 3)]
    gem_kinds = ["gema", "gemd", "geme", "gemr", "gems", "gemt", "gemz"]
    uber = {"pk1", "pk2", "pk3", "tes", "ceh", "bet", "fed", "toa", "xa1", "xa2", "xa3", "xa4", "xa5", "um1", "um2", "um3", "um4", "um5", "um6",
            "ua1", "ua2", "ua3", "ua4", "ua5", "std"}
    out.append("constexpr ItemClass ItemClasses[] {")
    seen = set()
    for file in ("weapons.txt", "armor.txt", "misc.txt"):
        for r in rows(folder, file):
            code = r.get("code", "")
            if not code or code in seen:
                continue
            seen.add(code)
            group, slot, tier, gem, grade = 6, 0, 0, 0, 0
            if any_of(r, ["misl"]) or any_of(r, ["poti", "scro", "book", "key", "gold", "herb", "elix", "body", "play", "tpot"]):
                group = 7  # consumables and junk: not tracked by default
            if file != "misc.txt" or any_of(r, ["ring", "amul"]):
                group = 0
                slot = next((s for t, s in slots if any_of(r, [t])), 3)
                tiers = [r.get("normcode"), r.get("ubercode"), r.get("ultracode")]
                tier = tiers.index(code) + 1 if code in tiers else 0
                if any_of(r, ["misl"]):
                    group, slot = 7, 0
            elif any_of(r, ["rune"]):
                group = 1
            elif any_of(r, ["gem"]):
                group = 2
                gem = next((i + 1 for i, k in enumerate(gem_kinds) if any_of(r, [k])), 0)
                grade = next((i + 1 for i in range(5) if any_of(r, [f"gem{i}"])), 0)
            elif any_of(r, ["char", "torc"]):
                group = 3
            elif any_of(r, ["jewl"]):
                group = 4
            elif code in uber:
                group = 5
            out.append(f"\t{{ {c(code)}, {group}, {slot}, {tier}, {gem}, {grade} }},")
    out.append("};")
    out.append("")

    # Runes r01..r33 in order, short English names for min_rune.
    misc = {r["code"]: r["name"] for r in rows(folder, "misc.txt") if r.get("code")}
    names = [misc[f"r{i:02d}"].replace(" Rune", "") for i in range(1, 34)]
    out.append("constexpr const char* RuneNames[] { " + ", ".join(c(n) for n in names) + " };")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
