# Builds the panel's packaged art from the stash frame Grail On! ships
# (Expanded Stash Plus's stash, 1687x1801, 16x16 cells of 98). The panel is
# 1162x1507, the size of the game's left panels (the frame of Run Counter's
# stats window): the stash's corners, edges and gold inner line, cropped
# (never scaled) to that size. Written to src/frame_art.inc as 256-colour
# pictures (a palette and one byte per pixel), in pieces:
#   top (1162x178) and bottom (1162x56): the bands;
#   left and right (59x1273): the edges between them;
#   slot: one empty cell (98x98), tiled under the charm grid.
# The plugin draws the dark stone inside and puts the pieces around it.
# Usage: python3 make_art.py <stash.png> <frame_art.inc>
import sys
from pathlib import Path
from PIL import Image

stash = Image.open(sys.argv[1]).convert("RGBA")
pieces = []
W, H = 1162, 1507
sw, sh = stash.size
# Inside the gold line: x 59..1627, y 178..1744 on the stash.
left, right, top, bottom = 59, sw - 1628, 178, sh - 1745
corner = 160  # the top and bottom corners keep their ornaments


def save(image, name):
    q = image.quantize(256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    palette = q.getpalette()[:768]
    pieces.append((name, q.width, q.height, palette + [0] * (768 - len(palette)), q.tobytes()))


# Top band (frame and title band) and bottom frame: corners, then the middle cropped.
for (sy, h, name) in ((0, top, "Top"), (sh - bottom, bottom, "Bottom")):
    band = Image.new("RGBA", (W, h))
    band.paste(stash.crop((0, sy, corner, sy + h)), (0, 0))
    band.paste(stash.crop((sw - corner, sy, sw, sy + h)), (W - corner, 0))
    mid = W - 2 * corner
    x0 = (sw - mid) // 2
    band.paste(stash.crop((x0, sy, x0 + mid, sy + h)), (corner, 0))
    save(band, name)
# Side edges with the gold line, cropped from the middle rows.
span = H - top - bottom
y0 = top + 40
save(stash.crop((0, y0, left, y0 + span)), "Left")
save(stash.crop((sw - right, y0, sw, y0 + span)), "Right")
# One cell: the first one of the grid.
save(stash.crop((left, top, left + 98, top + 98)), "Slot")
out = ["// Generated by tools/make_art.py from Grail On!'s stash art. Do not edit.",
       "struct ArtPiece { int width, height; const unsigned char* palette; const unsigned char* pixels; };"]
for name, w, h, palette, pixels in pieces:
    out.append(f"constexpr unsigned char {name}Palette[] {{" + ",".join(map(str, palette)) + "};")
    out.append(f"constexpr unsigned char {name}Pixels[] {{")
    for i in range(0, len(pixels), 64):
        out.append("\t" + ",".join(map(str, pixels[i:i + 64])) + ",")
    out.append("};")
    out.append(f"constexpr ArtPiece {name}Art {{ {w}, {h}, {name}Palette, {name}Pixels }};")
Path(sys.argv[2]).write_text("\n".join(out) + "\n")
print("frame pieces for", (W, H))
